import {chromium} from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';

const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const report={passed:false,errors:[]};
try{
 const page=await browser.newPage({viewport:{width:1280,height:800}});
 page.on('pageerror',error=>report.errors.push(error.message));
 await page.goto('http://127.0.0.1:5173/?scene=grand-palace&trial=1&test=1');
 await page.click('#account-trial');
 await page.waitForFunction(()=>window.__gameDebug?.ready,null,{timeout:180000});
 await page.waitForSelector('#world-loading',{state:'detached',timeout:180000});
 await page.waitForSelector('#sky-entry:not([hidden])',{timeout:180000});
 await page.evaluate(async()=>{const {skyLaunch}=await import('/src/sky-terminal.js');__raceFixture({x:skyLaunch.x,z:skyLaunch.z,groundY:skyLaunch.y,yaw:skyLaunch.yaw,speed:0,jumpY:0,mode:'explore'});});
 await page.waitForTimeout(150);
 await page.evaluate(()=>__skyFixture.start(0,true));
 await page.waitForFunction(()=>window.__skyDebug?.clips>0&&!__skyDebug.paused&&!__skyDebug.transfer,null,{timeout:180000});
 await page.evaluate(()=>__skyFixture.set({speed:0,assisted:false,y:400}));
 await page.waitForTimeout(200);
 const before=await page.evaluate(()=>({yaw:__skyDebug.yaw,y:__skyDebug.y,assisted:__skyDebug.assisted}));
 await page.mouse.move(620,380);await page.mouse.down();await page.mouse.move(790,310,{steps:18});await page.mouse.up();
 await page.waitForTimeout(500);
 const after=await page.evaluate(()=>({yaw:__skyDebug.yaw,y:__skyDebug.y,assisted:__skyDebug.assisted}));
 report.drag={before,after};
 assert.ok(after.yaw<before.yaw-.08,'Dragging right must turn the real flight right');
 assert.ok(after.y>before.y+.1,'Dragging up must climb');
 assert.equal(after.assisted,false);
 const released=await page.evaluate(()=>({yaw:__skyDebug.yaw,y:__skyDebug.y}));
 await page.waitForTimeout(700);
 const settled=await page.evaluate(()=>({yaw:__skyDebug.yaw,y:__skyDebug.y}));
 assert.ok(Math.abs(settled.yaw-released.yaw)<.02,'Release must settle without continuous turning');
 assert.ok(Math.abs(settled.y-released.y)<.15,'Release must stop vertical drift');
 report.release={released,settled};
 await page.click('#sky-map');
 const paused=await page.evaluate(()=>({yaw:__skyDebug.yaw,y:__skyDebug.y}));
 await page.mouse.move(20,370);await page.mouse.down();await page.mouse.move(160,290,{steps:12});await page.mouse.up();await page.waitForTimeout(200);
 assert.deepEqual(await page.evaluate(()=>({yaw:__skyDebug.yaw,y:__skyDebug.y})),paused,'Flight menu must ignore drags');
 await page.click('#sky-close');
 await page.evaluate(()=>__skyFixture.set({assisted:true,speed:0}));
 await page.mouse.move(600,350);await page.mouse.down();await page.mouse.move(500,380,{steps:12});await page.mouse.up();await page.waitForTimeout(150);
 assert.equal(await page.evaluate(()=>__skyDebug.assisted),false,'Dragging must take over from assisted navigation');
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(150);
 await page.click('#sky-brake');
 const touchBefore=await page.evaluate(()=>__skyDebug.yaw);
 const right=page.locator('[data-sky-key="KeyD"]');await right.hover();await page.mouse.down();await page.waitForTimeout(350);await page.mouse.up();await page.waitForTimeout(100);
 assert.ok(await page.evaluate(()=>__skyDebug.yaw)<touchBefore-.1,'HUD turn buttons must still steer');
 const cdp=await page.context().newCDPSession(page);
 const mobileBefore=await page.evaluate(()=>__skyDebug.yaw);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:150,y:350,id:1}]});
 for(let i=1;i<=12;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:150+i*7,y:350-i*2,id:1}]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.waitForTimeout(600);
 assert.ok(await page.evaluate(()=>__skyDebug.yaw)<mobileBefore-.15,'Touch drag on the world must steer right');
 report.mobileTouchDrag=true;
 assert.deepEqual(report.errors,[]);
 report.passed=true;
 await page.screenshot({path:'reports/sky-pointer-mobile.jpg'});
}catch(error){report.failure=error.message;process.exitCode=1;}
finally{fs.writeFileSync('reports/sky-pointer-check.json',JSON.stringify(report,null,2));await browser.close();}
console.log(JSON.stringify(report));
